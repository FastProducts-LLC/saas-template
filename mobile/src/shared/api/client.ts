// Native port of frontend/src/shared/api/client.ts. Same contract — attaches
// the in-memory access token, transparently refreshes once on a 401, and
// normalizes every failure into a catalog-aware ApiError — with one structural
// difference: there is no httpOnly cookie jar on native, so the refresh token
// lives in SecureStore and travels in the request/response BODY. Every request
// sends `X-Client: mobile`, which is what makes the backend return refresh
// tokens in the body instead of a cookie.
//
// Mutating requests get an Idempotency-Key that is REUSED across retries —
// both the catalog-driven retry below and the 401-refresh retry — so a
// retried timed-out POST can never double-execute (the backend replays the
// first response instead).
//
// Platform adapters (SecureStore, expo-crypto, base URL) are injected via
// configureApi() in setup.ts, keeping this module pure and unit-testable.
//
// NOTE: errorCatalog.ts is GENERATED by scripts/gen_errors.py — edit
// shared/errors.toml, never the file itself.

import {
  errorCatalog,
  formatErrorMessage,
  isErrorCode,
  type CatalogEntry,
  type ErrorCode,
  type ErrorParams,
} from "./errorCatalog";
import { publishError } from "./errorBus";

export interface RefreshTokenStore {
  get(): Promise<string | null>;
  set(token: string | null): Promise<void>;
}

export interface ApiConfig {
  baseUrl: string;
  refreshTokens: RefreshTokenStore;
  randomUUID: () => string;
  /** Called when a refresh is rejected while a session existed — the session
   * provider signs the user out and routes to the sign-in screen. */
  onSessionExpired?: () => void;
}

let config: ApiConfig | null = null;

export function configureApi(next: ApiConfig): void {
  config = next;
}

function cfg(): ApiConfig {
  if (!config) throw new Error("configureApi() must run before any API call");
  return config;
}

let accessToken: string | null = null;

export function setAccessToken(token: string | null): void {
  accessToken = token;
}

export function getAccessToken(): string | null {
  return accessToken;
}

/** Persist (or clear) the rotating refresh token in secure storage. */
export function storeRefreshToken(token: string | null): Promise<void> {
  return cfg().refreshTokens.set(token);
}

export function getStoredRefreshToken(): Promise<string | null> {
  return cfg().refreshTokens.get();
}

// Bodyless / non-catalog responses (proxy 502s, oversized uploads rejected
// before FastAPI) still map onto catalog copy by status.
const STATUS_FALLBACK: Record<number, ErrorCode> = {
  400: "ERR_REQ_001",
  401: "ERR_AUTH_003",
  403: "ERR_PERM_001",
  404: "ERR_REQ_002",
  409: "ERR_REQ_003",
  413: "ERR_REQ_005",
  422: "ERR_VAL_001",
  429: "ERR_REQ_004",
  500: "ERR_SRV_001",
  502: "ERR_SRV_002",
  503: "ERR_SRV_003",
  504: "ERR_SRV_002",
};

export class ApiError extends Error {
  /** Epoch ms when a 429's Retry-After elapses — null when the server
   * didn't say. Screens disable the triggering control until then. */
  public retryAt: number | null = null;
  /** Server says repeating the same request may succeed (envelope `retryable`). */
  public retryable = false;

  constructor(
    public status: number,
    /** The code exactly as the server sent it — may be newer than this
     * build's catalog (app-store lag); copy then falls back by HTTP status. */
    public code: string,
    message: string,
    /** Correlation id (`instance` in the envelope) — what users report. */
    public errorId: string | null = null,
    /** Per-field validation messages for form binding (422s). */
    public fields: Record<string, string> = {},
    /** Values for the catalog's param-specific copy (envelope `params`). */
    public params: ErrorParams = {},
  ) {
    super(message);
  }

  /** Catalog entry for the code, or the generic entry for the HTTP status
   * when this build doesn't know the code — vetted copy, never server text. */
  get catalog(): CatalogEntry {
    if (isErrorCode(this.code)) return errorCatalog[this.code];
    return errorCatalog[STATUS_FALLBACK[this.status] ?? "ERR_REQ_001"];
  }

  /** Friendly headline — param-specific copy when every value is present. */
  get userMessage(): string {
    return formatErrorMessage(this.catalog, this.params);
  }

  get actionStep(): string {
    return this.catalog.action;
  }

  get severity(): CatalogEntry["severity"] {
    return this.catalog.severity;
  }

  get display(): CatalogEntry["display"] {
    return this.catalog.display;
  }

  get retry(): { afterMs: number; max: number } | null {
    return this.catalog.retry;
  }

  /** What users quote to support: "ERR_BILL_002 · e7f3a2b1". */
  get reference(): string {
    return this.errorId ? `${this.code} · ${this.errorId}` : this.code;
  }

  /** One-line report for a "Copy details" action. */
  get details(): string {
    return [
      this.reference,
      new Date().toISOString(),
      `HTTP ${this.status}`,
      this.message,
    ].join(" | ");
  }
}

async function rawFetch(path: string, options: RequestInit): Promise<Response> {
  const headers = new Headers(options.headers);
  headers.set("X-Client", "mobile");
  if (options.body && !headers.has("Content-Type")) {
    headers.set("Content-Type", "application/json");
  }
  if (accessToken) {
    headers.set("Authorization", `Bearer ${accessToken}`);
  }
  return fetch(`${cfg().baseUrl}${path}`, { ...options, headers });
}

// Single-flight: concurrent 401s share one refresh call. Without this, N
// parallel requests fire N refreshes; with rotating (single-use) refresh
// tokens every refresh after the first fails and logs the user out.
let refreshInFlight: Promise<boolean> | null = null;

export function tryRefresh(): Promise<boolean> {
  refreshInFlight ??= doRefresh().finally(() => {
    refreshInFlight = null;
  });
  return refreshInFlight;
}

async function doRefresh(): Promise<boolean> {
  const { baseUrl, refreshTokens, onSessionExpired } = cfg();
  const stored = await refreshTokens.get();
  if (!stored) {
    setAccessToken(null);
    return false;
  }
  try {
    const res = await fetch(`${baseUrl}/auth/refresh`, {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-Client": "mobile" },
      body: JSON.stringify({ refresh_token: stored }),
    });
    if (res.status === 401) {
      // The token is dead (revoked / expired / rotated elsewhere). A failed
      // refresh is only "session expired" when there WAS a session; at app
      // start (logged out) it's the normal path — stay quiet.
      if (accessToken) {
        publishError(new ApiError(401, "ERR_AUTH_002", "Session expired."));
      }
      setAccessToken(null);
      await refreshTokens.set(null);
      onSessionExpired?.();
      return false;
    }
    if (!res.ok) return false; // transient (429/5xx) — keep the token, fail this round
    const data = await res.json();
    setAccessToken(data.access_token);
    // Rotation: the old token was just revoked server-side — losing the new
    // one here would strand the session, so persist before returning.
    await refreshTokens.set(data.refresh_token ?? stored);
    return true;
  } catch {
    return false; // offline — the original request's error handling covers it
  }
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

async function parseError(res: Response): Promise<ApiError> {
  const body = await res.json().catch(() => ({}));
  // Keep an unknown-but-well-formed code verbatim (support needs the real
  // one); ApiError.catalog falls back by status for the copy.
  const code =
    typeof body.code === "string" && /^ERR_[A-Z]+_\d{3}$/.test(body.code)
      ? body.code
      : (STATUS_FALLBACK[res.status] ?? "ERR_REQ_001");
  const error = new ApiError(
    res.status,
    code,
    body.detail ?? body.title ?? res.statusText,
    typeof body.instance === "string"
      ? body.instance
      : (res.headers.get("X-Request-ID") ?? null),
    isPlainObject(body.fields) ? (body.fields as Record<string, string>) : {},
    isPlainObject(body.params) ? (body.params as ErrorParams) : {},
  );
  error.retryable = body.retryable === true;
  const retryAfterMs =
    typeof body.retry_after_ms === "number"
      ? body.retry_after_ms
      : Number(res.headers.get("Retry-After")) * 1000;
  if (res.status === 429 && Number.isFinite(retryAfterMs) && retryAfterMs > 0) {
    error.retryAt = Date.now() + retryAfterMs;
  }
  return error;
}

const MUTATING = new Set(["POST", "PUT", "PATCH", "DELETE"]);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export async function api<T>(
  path: string,
  options: RequestInit = {},
): Promise<T> {
  const method = (options.method ?? "GET").toUpperCase();
  const mutating = MUTATING.has(method);
  if (mutating) {
    // One key per logical operation, reused by every retry below.
    const headers = new Headers(options.headers);
    if (!headers.has("Idempotency-Key"))
      headers.set("Idempotency-Key", cfg().randomUUID());
    options = { ...options, headers };
  }

  let attempt = 0;
  for (;;) {
    let error: ApiError;
    try {
      let res = await rawFetch(path, options);
      if (res.status === 401 && !path.startsWith("/auth/")) {
        if (await tryRefresh()) {
          res = await rawFetch(path, options);
        }
      }
      if (res.ok) {
        return res.status === 204 ? (undefined as T) : res.json();
      }
      error = await parseError(res);
    } catch (err) {
      if (err instanceof ApiError) throw err; // never re-wrap
      error = new ApiError(0, "ERR_NET_001", `Network error: ${String(err)}`);
    }

    // Catalog-driven retry, mutations only (queries retry via TanStack Query,
    // which re-calls api() — fine for GETs, unsafe for POSTs without the
    // reused Idempotency-Key this loop preserves).
    const retry = error.retry;
    if (mutating && retry && attempt < retry.max) {
      attempt += 1;
      await sleep(retry.afterMs * attempt);
      continue;
    }

    publishError(error);
    throw error;
  }
}

// Binary variant of api(): same auth + refresh handling, returns a data URI.
// Needed because <Image source> can't attach the Bearer token — callers fetch
// the bytes and render the data URI directly.
export async function apiDataUri(path: string): Promise<string> {
  let res: Response;
  try {
    res = await rawFetch(path, {});
    if (res.status === 401 && (await tryRefresh())) {
      res = await rawFetch(path, {});
    }
  } catch (err) {
    const error = new ApiError(
      0,
      "ERR_NET_001",
      `Network error: ${String(err)}`,
    );
    publishError(error);
    throw error;
  }
  if (!res.ok) {
    const error = await parseError(res);
    publishError(error);
    throw error;
  }
  const blob = await res.blob();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = () =>
      reject(new ApiError(0, "ERR_NET_001", "Failed to read file."));
    reader.readAsDataURL(blob);
  });
}
